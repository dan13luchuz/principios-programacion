
a = 10
b = 5

# ------------------------------------------
# OPERADORES ARITMÉTICOS
# ------------------------------------------
print("--- Operadores aritméticos ---")

print("Suma:", a + b)              # 10 + 5 = 15
print("Resta:", a - b)             # 10 - 5 = 5
print("Multiplicación:", a * b)    # 10 * 5 = 50
print("División:", a / b)          # 10 / 5 = 2.0
print("División entera:", a // b)  # 10 // 5 = 2
print("Módulo:", a % b)            # Residuo de 10 / 5 = 0
print("Potencia:", a ** b)         # 10 elevado a la 5 = 100000

# ------------------------------------------
# OPERADORES DE COMPARACIÓN
# ------------------------------------------
print("\n--- Operadores de comparación ---")

print("a es igual a b:", a == b)          # False
print("a es diferente de b:", a != b)     # True
print("a es mayor que b:", a > b)         # True
print("a es menor que b:", a < b)         # False
print("a es mayor o igual que b:", a >= b)  # True
print("a es menor o igual que b:", a <= b)  # False

# ------------------------------------------
# OPERADORES LÓGICOS
# ------------------------------------------
print("\n--- Operadores lógicos ---")

x = True
y = False

print("x and y:", x and y)  # True solo si ambos son True
print("x or y:", x or y)    # True si al menos uno es True
print("not x:", not x)      # Invierte el valor de x